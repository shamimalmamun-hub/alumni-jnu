/**
 * Given a batch string (e.g. "১ম ব্যাচ", "1st Batch", "24th", "২৪ তম ব্যাচ"), finds the matching session in Bengali.
 */
export function getSessionByBatch(batchStr: string): string | null {
  if (!batchStr) return null;
  const clean = batchStr.trim();
  const found = BATCH_SESSION_LIST.find(
    (item) =>
      item.batchBn === clean ||
      item.batchBn.replace(/\s+/g, '') === clean.replace(/\s+/g, '') ||
      item.batchEn.toLowerCase() === clean.toLowerCase() ||
      clean.includes(item.batchBn) ||
      clean.includes(item.batchEn) ||
      clean.startsWith(item.batchNumber.toString()) ||
      clean.startsWith(item.batchBn.replace(' ব্যাচ', '').trim())
  );
  return found ? found.sessionBn : null;
}

/**
 * Given a session string (e.g. "1997-98", "১৯৯৭-১৯৯৮"), finds the matching batch in Bengali.
 */
export function getBatchBySession(sessionStr: string): string | null {
  if (!sessionStr) return null;
  const clean = sessionStr.trim().replace(/\s+/g, '');
  const found = BATCH_SESSION_LIST.find(
    (item) =>
      clean.includes(item.sessionEn) ||
      clean.includes(item.sessionBn) ||
      clean.includes(item.sessionShortBn) ||
      item.sessionBn.replace(/\s+/g, '') === clean ||
      item.sessionShortBn.replace(/\s+/g, '') === clean
  );
  return found ? found.batchBn : null;
}
