// Convert Bengali digits (০-৯) to English digits (0-9)
const bnToEnDigits = (str: string): string => {
  const banglaDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return str.replace(/[০-৯]/g, (d) => String(banglaDigits.indexOf(d)));
};

