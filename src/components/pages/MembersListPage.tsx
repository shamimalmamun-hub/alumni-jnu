    const rawQuery = searchQuery.trim();
    if (!rawQuery) {
      const matchesProgram = programFilter === 'all' || m.program === programFilter;
      const matchesSession = sessionFilter === 'all' || m.session === sessionFilter;
      return matchesProgram && matchesSession;
    }

    // Convert query (Bengali/English digits & alphanumeric)
    const qEn = bnToEnDigits(rawQuery).toLowerCase().replace(/[^a-z0-9]/gi, '');
