  // When an admin deletes a member from the admin dashboard, Firestore onSnapshot immediately updates this list
  useEffect(() => {
    let unsubscribe = () => {};
    try {
      const q = collection(db, 'memberships');
      unsubscribe = onSnapshot(
        q,
        (snapshot) => {
          if (!snapshot.empty) {
            const dbList: MemberRecord[] = [];
            snapshot.forEach((docSnap) => {
              const data = docSnap.data() as any;
              // Include registered/approved members (exclude only if explicitly rejected)
              if (data.status !== 'rejected') {
                const autoGeneratedFormNo = `BOT-ALUMNI-${(Math.abs(docSnap.id.split('').reduce((a, b) => (((a << 5) - a) + b.charCodeAt(0)) | 0, 0)) % 9000 + 1000)}`;
                dbList.push({
                  id: docSnap.id,
                  formNo: data.formNo || autoGeneratedFormNo,
                  applicantNameBn: data.applicantNameBn || data.fullName || 'নামহীন সদস্য',
                  applicantNameEn: data.applicantNameEn || '',
                  program: data.program || 'bsc_honours',
                  academicYear: data.academicYear || '',
                  session: data.session || data.batch || '',
                  classRoll: data.classRoll || '',
                  regNumber: data.regNumber || '',
                  mobile: data.mobile || '',
                  email: data.email || '',
                  bloodGroup: data.bloodGroup || '',
                  district: data.district || '',
                  village: data.village || '',
                  currentAddress: data.currentAddress || data.presentAddress || '',
                  paymentMethod: data.paymentMethod || 'Manual',
                  transactionId: data.transactionId || '',
                  date: data.date || (data.createdAt ? new Date(data.createdAt).toLocaleDateString('bn-BD') : ''),
                  userPhotoUrl: data.userPhotoUrl || '',
                  status: data.status || 'approved',
                });
              }
            });

            // Sort by formNo or registration date
            dbList.sort((a, b) => (b.formNo || '').localeCompare(a.formNo || ''));
            setMembers(dbList);
          } else {
            setMembers([]);
          }
          setLoading(false);
        },
        (error) => {
          console.warn('Firestore real-time load notice:', error);
          setLoading(false);
        }
      );
    } catch (e) {
      console.warn('Firestore subscription error:', e);
      setLoading(false);
    }

    return () => unsubscribe();
  }, []);

  // Reset to page 1 whenever filters or search query change
  useEffect(() => {
    setCurrentPage(1);
  }, [searchQuery, programFilter, sessionFilter]);

  // Filter list: Search strictly by Registration Form Number / Last 4 Digits only
